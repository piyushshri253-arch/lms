export function getDefaultPermissionsForRole(role: UserRole): PermissionKey[] {
  return DEFAULT_ROLE_PERMISSIONS[role] || DEFAULT_ROLE_PERMISSIONS.STUDENT;
}

export function hasPermission(
  userRole: UserRole,
  userPermissions: string[] = [],
  requiredPermission: PermissionKey
): boolean {
  if (userRole === 'SUPER_ADMIN') return true;
  if (userPermissions.includes('ALL')) return true;
  if (userPermissions.includes(requiredPermission)) return true;
  const defaultPerms = DEFAULT_ROLE_PERMISSIONS[userRole] || [];
  return defaultPerms.includes(requiredPermission);
}
